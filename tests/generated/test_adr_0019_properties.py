def _is_excluded(path: Path) -> bool:
    """Check if path should be excluded from scanning."""
    parts = path.parts
    for part in parts:
        if part in SKIP_DIRS:
            return True
        if part.startswith(".") and part != ".":
            return True
    return False


def _is_print_allowed(rel_path: str) -> bool:
    """Check if print() is allowed in this file per allowlist."""
    for d in PRINT_ALLOWED_DIRS:
        if rel_path.startswith(d + "/") or rel_path.startswith(d + "\\"):
            return True
    for d in PRINT_ALLOWED_AGENT_DIRS:
        if rel_path.startswith(d + "/") or rel_path.startswith(d + "\\"):
            return True
    return False


def _line_has_noqa(content: str, lineno: int) -> bool:
    """Check if a specific line has # noqa: ADR-0019."""
    lines = content.splitlines()
    if 0 < lineno <= len(lines):
        return "noqa" in lines[lineno - 1] and "ADR-0019" in lines[lineno - 1]
    return False


def _get_production_files(repo_root: Path) -> list[Path]:
    """Get production Python files, excluding non-production dirs."""
    files = []
    for py_file in repo_root.rglob("*.py"):
        rel = py_file.relative_to(repo_root)
        if _is_excluded(rel):
            continue
        # Also skip test files
        if any(part.startswith("test_") or part == "tests" for part in rel.parts):
            continue
        files.append(py_file)
    return files


