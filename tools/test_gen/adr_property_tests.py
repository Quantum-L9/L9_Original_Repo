# Directories to skip entirely — matches .l9-allowlist.yaml auto_fix_skip_dirs
SKIP_DIRS = {
    "venv", ".venv", ".git", "__pycache__", "node_modules",
    "_archived", ".backup", "current_work", ".cursor", "private",
    "codegen",
}

# Dirs where print() is allowed — matches .l9-allowlist.yaml adr_0019_print_allowed_dirs
PRINT_ALLOWED_DIRS = {
    "ci", "scripts", "tools", "workflows", "bootstrap", "examples",
    "local_dashboard",
}

# Agent dirs where print() is allowed for CLI output
PRINT_ALLOWED_AGENT_DIRS = {
    "agents/cursor",
}


def _is_excluded(path: Path) -> bool:
    """Check if path should be excluded from scanning."""
    parts = path.parts
    for part in parts:
        if part in SKIP_DIRS:
            return True
        if part.startswith(".") and part != ".":
            return True
    return False


def _is_print_allowed(rel_path: str) -> bool:
    """Check if print() is allowed in this file per allowlist."""
    for d in PRINT_ALLOWED_DIRS:
        if rel_path.startswith(d + "/") or rel_path.startswith(d + "\\\\"):
            return True
    for d in PRINT_ALLOWED_AGENT_DIRS:
        if rel_path.startswith(d + "/") or rel_path.startswith(d + "\\\\"):
            return True
    return False


def _line_has_noqa(content: str, lineno: int) -> bool:
    """Check if a specific line has # noqa: ADR-0019."""
    lines = content.splitlines()
    if 0 < lineno <= len(lines):
        return "noqa" in lines[lineno - 1] and "ADR-0019" in lines[lineno - 1]
    return False


def _get_production_files(repo_root: Path) -> list[Path]:
    """Get production Python files, excluding non-production dirs."""
    files = []
    for py_file in repo_root.rglob("*.py"):
        rel = py_file.relative_to(repo_root)
        if _is_excluded(rel):
            continue
        # Also skip test files
        if any(part.startswith("test_") or part == "tests" for part in rel.parts):
            continue
        files.append(py_file)
    return files


class TestADR0019StructlogEnforcement:
    """Property tests ensuring ADR-0019 compliance."""

    @pytest.fixture(autouse=True)
    def setup(self):
        """Setup test fixtures."""
        self.repo_root = Path(__file__).parent.parent.parent
        self.production_files = _get_production_files(self.repo_root)

    def test_no_print_statements_in_production(self):
        """Property: No print() calls in production code (respects allowlist + noqa)."""
        violations = []

        for py_file in self.production_files:
            rel_path = str(py_file.relative_to(self.repo_root))

            # Skip files in print-allowed directories
            if _is_print_allowed(rel_path):
                continue

            try:
                content = py_file.read_text()
                tree = ast.parse(content, filename=str(py_file))

                for node in ast.walk(tree):
                    if isinstance(node, ast.Call):
                        if isinstance(node.func, ast.Name) and node.func.id == "print":
                            # Respect noqa suppression
                            if _line_has_noqa(content, node.lineno):
                                continue
                            violations.append({
                                "file": rel_path,
                                "line": node.lineno,
                                "violation": "print() call found"
                            })
            except SyntaxError:
                continue
            except Exception as e:
                logger.warning("parse_failed", file=str(py_file), error=str(e))

        if violations:
            msg = "\\n".join(
                f"  {v['file']}:{v['line']} - {v['violation']}"
                for v in violations
            )
            pytest.fail(f"ADR-0019 Violation: print() statements found:\\n{msg}")

    def test_no_stdlib_logging_imports(self):
        """Property: No imports from stdlib logging module (respects noqa + allowlist)."""
        violations = []

        for py_file in self.production_files:
            rel_path = str(py_file.relative_to(self.repo_root))

            # Skip files in allowlisted directories (CLI tools may use stdlib logging)
            if _is_print_allowed(rel_path):
                continue

            try:
                content = py_file.read_text()
                tree = ast.parse(content, filename=str(py_file))

                for node in ast.walk(tree):
                    # Check for: import logging
                    if isinstance(node, ast.Import):
                        for alias in node.names:
                            if alias.name == "logging":
                                if _line_has_noqa(content, node.lineno):
                                    continue
                                violations.append({
                                    "file": str(py_file.relative_to(self.repo_root)),
                                    "line": node.lineno,
                                    "violation": f"import {alias.name}"
                                })

                    # Check for: from logging import X
                    if isinstance(node, ast.ImportFrom):
                        if node.module == "logging":
                            if _line_has_noqa(content, node.lineno):
                                continue
                            violations.append({
                                "file": str(py_file.relative_to(self.repo_root)),
                                "line": node.lineno,
                                "violation": f"from logging import ..."
                            })
            except SyntaxError:
                continue
            except Exception as e:
                logger.warning("parse_failed", file=str(py_file), error=str(e))

        if violations:
            msg = "\\n".join(
                f"  {v['file']}:{v['line']} - {v['violation']}"
                for v in violations
            )
            pytest.fail(f"ADR-0019 Violation: stdlib logging imports found:\\n{msg}")

    def test_structlog_logger_pattern(self):
        """Property: Verify structlog.get_logger() is used correctly."""
        compliant_files = []

        for py_file in self.production_files:
            try:
                content = py_file.read_text()

                # Check for structlog usage
                if "structlog" not in content:
                    continue

                # Check for correct pattern: logger = structlog.get_logger()
                if re.search(r'logger\\s*=\\s*structlog\\.get_logger\\(\\)', content):
                    compliant_files.append(str(py_file.relative_to(self.repo_root)))

            except Exception as e:
                logger.warning("pattern_check_failed", file=str(py_file), error=str(e))

        logger.info("structlog_pattern_check", compliant_files=len(compliant_files))

        # This is informational - not a hard failure
        assert len(compliant_files) >= 0, "Sanity check"

    @given(st.text(min_size=10, max_size=500))
    @settings(
        max_examples=200,
        suppress_health_check=[HealthCheck.function_scoped_fixture]
    )
    def test_code_samples_no_print(self, code_sample: str):
        """Fuzz test: Random code samples should not contain print()."""
        # Skip if not valid Python
        try:
            tree = ast.parse(code_sample)
        except SyntaxError:
            return  # Invalid syntax is fine for fuzzing

        # Check for print calls
        for node in ast.walk(tree):
            if isinstance(node, ast.Call):
                if isinstance(node.func, ast.Name) and node.func.id == "print":
                    pytest.fail(
                        f"Fuzz test found print() in generated code:\\n{code_sample[:100]}"
                    )

    @given(st.text(min_size=20, max_size=200, alphabet=st.characters(whitelist_categories=("Lu", "Ll"))))
    @settings(max_examples=100)
    def test_log_context_binding(self, context_key: str):
        """Property test: Structlog context binding should work with any string key."""
        try:
            log = structlog.get_logger()
            bound = log.bind(**{context_key: "test_value"})

            # Verify binding worked
            assert bound is not None

        except Exception as e:
            # Some keys might be invalid, that's fine
            if "invalid" not in str(e).lower():
                pytest.fail(f"Unexpected error binding context key '{context_key}': {e}")


