def load_adr_schema(adr_file: Path) -> dict[str, Any]:
    """Load ADR YAML schema.

    Args:
        adr_file: Path to ADR YAML file

    Returns:
        Parsed ADR schema
    """
    try:
        with open(adr_file) as f:
            return yaml.safe_load(f)
    except Exception as e:
        logger.error("adr_load_failed", file=str(adr_file), error=str(e))
        return {}


