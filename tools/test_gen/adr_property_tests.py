def emit_test_file(adr_num: str, test_code: str, output_dir: Path) -> Path:
    """Write generated test file to disk.

    Args:
        adr_num: ADR number (e.g., "0019")
        test_code: Complete test file content
        output_dir: Output directory (tests/generated/)

    Returns:
        Path to written test file
    """
    output_dir.mkdir(parents=True, exist_ok=True)

    test_file = output_dir / f"test_adr_{adr_num}_properties.py"
    test_file.write_text(test_code)

    logger.info("test_file_generated", path=str(test_file))
    return test_file


def main():
    """CLI entry point."""
    parser = argparse.ArgumentParser(
        description="Generate property-based tests from ADR schemas"
    )
    parser.add_argument(
        "--repo-root", type=Path, default=Path("."), help="Repository root directory"
    )
    parser.add_argument(
        "--adr", type=str, help="Generate tests for specific ADR (e.g., '0019')"
    )
    parser.add_argument(
        "--all", action="store_true", help="Generate tests for all ADRs"
    )
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    adr_dir = repo_root / "readme" / "adr" / "rules"
    output_dir = repo_root / "tests" / "generated"

    # Define generators for specific ADRs
    generators = {
        "0019": generate_structlog_tests,
        "0006": generate_packet_envelope_tests,
    }

    if args.adr:
        # Generate for specific ADR
        if args.adr not in generators:
            logger.error("no_generator", adr=args.adr)
            print(f"❌ No test generator for ADR-{args.adr}")
            return 1

        adr_file = adr_dir / f"{args.adr}.yaml"
        if not adr_file.exists():
            logger.warning("adr_file_not_found", path=str(adr_file))
            rules = {}
        else:
            rules = load_adr_schema(adr_file)

        generator = generators[args.adr]
        test_code = generator(args.adr, rules)
        test_file = emit_test_file(args.adr, test_code, output_dir)

        print(f"✅ Generated: {test_file}")

    elif args.all:
        # Generate for all supported ADRs
        generated = []
        for adr_num, generator in generators.items():
            adr_file = adr_dir / f"{adr_num}.yaml"
            rules = load_adr_schema(adr_file) if adr_file.exists() else {}

            test_code = generator(adr_num, rules)
            test_file = emit_test_file(adr_num, test_code, output_dir)
            generated.append(test_file)

        print(f"\n✅ Generated {len(generated)} ADR property test files:")
        for f in generated:
            print(f"   {f.relative_to(repo_root)}")

    else:
        parser.print_help()
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
